#!/usr/bin/env bash
# Launch gpt-oss-120b in the verified AR+RMSNorm benchmark container.
# Usage: serve.sh <world_size> <hip_visible_devices> <comm_fusion_max_num_tokens> <ts_arnorm_backend> [extra serve args...]
# Example (ws=4, avoid noisy GPU3=HIP0, default fusion, auto->triton_shmem):
#   serve.sh 4 1,2,3,5 2048 auto
# GPU MAPPING (rocm-smi index -> HIP index, via PCI bus): 0->1 1->3 2->2 3->0 4->5 5->7 6->6 7->4
#   => rocm-smi GPU3 (periodic-burst noisy GPU) == HIP index 0. Exclude HIP 0 for ws<8.
set -euo pipefail
WS="${1:?world_size}"; HVD="${2:?hip_visible_devices}"; CAP="${3:-2048}"; BK="${4:-auto}"; shift 4 || true
PORT="${PORT:-8100}"
CONTAINER="${CONTAINER:-jeremwan-tokenspeed}"
NCCL_BLOCKING_WAIT="${TORCH_NCCL_BLOCKING_WAIT:-0}"
INKERNEL_BARRIER="${TS_TRITON_SHMEM_INKERNEL_BARRIER:-1}"
FOLD_COPYIN="${TS_TRITON_SHMEM_FOLD_COPYIN:-1}"
WORKGROUP_SYNC="${TS_TRITON_SHMEM_WORKGROUP_SYNC:-1}"
FOLD_NUM_WARPS="${TS_TRITON_SHMEM_FOLD_NUM_WARPS:-1}"
BARRIER_GRID="${TS_TRITON_SHMEM_BARRIER_GRID:-0}"
GRID_CAP="${TS_TRITON_SHMEM_GRID_CAP:--1}"
GRID_CAP_MIN_M="${TS_TRITON_SHMEM_GRID_CAP_MIN_M:--1}"
ONESHOT_MAX_M="${TS_TRITON_SHMEM_ONESHOT_MAX_M:-256}"
TRITON_AR_DISABLE="${TS_TRITON_AR_DISABLE:-0}"
TRITON_AR_WORKGROUP_SYNC="${TS_TRITON_AR_WORKGROUP_SYNC:-1}"
PROFILER_DIR="${TOKENSPEED_PROFILER_DIR:-/tmp}"
PROFILE_WITH_STACK="${TOKENSPEED_PROFILE_WITH_STACK:-1}"
KERNEL_PROFILE="${TOKENSPEED_KERNEL_PROFILE:-0}"
KERNEL_PROFILE_EARLY="${TOKENSPEED_KERNEL_PROFILE_EARLY:-0}"
KERNEL_PROFILE_EARLY_KEEP_ACTIVE="${TOKENSPEED_KERNEL_PROFILE_EARLY_KEEP_ACTIVE:-0}"
KERNEL_PROFILE_BEFORE_GRAPHS="${TOKENSPEED_KERNEL_PROFILE_BEFORE_GRAPHS:-0}"
KERNEL_PROFILE_GRAPH_SCOPES="${TOKENSPEED_KERNEL_PROFILE_GRAPH_SCOPES:-0}"
KERNEL_PROFILE_OUTPUT="${TOKENSPEED_KERNEL_PROFILE_OUTPUT:-profile}"
KERNEL_PROFILE_DATA="${TOKENSPEED_KERNEL_PROFILE_DATA:-tree}"
KERNEL_PROFILE_BACKEND="${TOKENSPEED_KERNEL_PROFILE_BACKEND:-}"
KERNEL_PROFILE_HOOK="${TOKENSPEED_KERNEL_PROFILE_HOOK:-triton}"
KERNEL_PROFILE_OUTPUT_FORMAT="${TOKENSPEED_KERNEL_PROFILE_OUTPUT_FORMAT:-}"
RUN_LABEL="${RUN_LABEL:-ws${WS}_cap${CAP}_${BK}}"
LOG_DIR="${LOG_DIR:-/home/jeremwan/ar_rmsnorm_e2e/logs}"
LOG="${LOG_DIR}/serve_${RUN_LABEL}.log"
KERNEL_PROFILE_OUTPUT_DIR="$(dirname "${KERNEL_PROFILE_OUTPUT}")"
if [[ "$KERNEL_PROFILE_BACKEND" == "rocprofiler" || "$KERNEL_PROFILE_BACKEND" == "roctracer" ]]; then
  DEVICE_VISIBILITY="ROCR_VISIBLE_DEVICES=${HVD}"
else
  DEVICE_VISIBILITY="HIP_VISIBLE_DEVICES=${HVD}"
fi

IFS=',' read -r -a DEVICES <<< "$HVD"
if [ "${#DEVICES[@]}" -ne "$WS" ]; then
  echo "world_size=$WS but HIP_VISIBLE_DEVICES contains ${#DEVICES[@]} devices" >&2
  exit 2
fi

docker exec "$CONTAINER" bash -lc "mkdir -p ${LOG_DIR} ${PROFILER_DIR} ${KERNEL_PROFILE_OUTPUT_DIR}; cd /home/jeremwan/tokenspeed && \
  printf 'RUN_ENV HVD=%s WS=%s CAP=%s BACKEND=%s BLOCKING_WAIT=%s INKERNEL=%s FOLD_COPYIN=%s WORKGROUP_SYNC=%s FOLD_NUM_WARPS=%s BARRIER_GRID=%s GRID_CAP=%s GRID_CAP_MIN_M=%s ONESHOT_MAX_M=%s TRITON_AR_DISABLE=%s TRITON_AR_WORKGROUP_SYNC=%s\\n' \
    '${HVD}' '${WS}' '${CAP}' '${BK}' '${NCCL_BLOCKING_WAIT}' '${INKERNEL_BARRIER}' \
    '${FOLD_COPYIN}' '${WORKGROUP_SYNC}' '${FOLD_NUM_WARPS}' '${BARRIER_GRID}' '${GRID_CAP}' '${GRID_CAP_MIN_M}' '${ONESHOT_MAX_M}' '${TRITON_AR_DISABLE}' '${TRITON_AR_WORKGROUP_SYNC}' > ${LOG}; \
  ${DEVICE_VISIBILITY} TS_ARNORM_BACKEND=${BK} HSA_ENABLE_IPC_MODE_LEGACY=1 \
  TORCH_NCCL_BLOCKING_WAIT=${NCCL_BLOCKING_WAIT} \
  TS_TRITON_SHMEM_INKERNEL_BARRIER=${INKERNEL_BARRIER} \
  TS_TRITON_SHMEM_FOLD_COPYIN=${FOLD_COPYIN} \
  TS_TRITON_SHMEM_WORKGROUP_SYNC=${WORKGROUP_SYNC} \
  TS_TRITON_SHMEM_FOLD_NUM_WARPS=${FOLD_NUM_WARPS} \
  TS_TRITON_SHMEM_BARRIER_GRID=${BARRIER_GRID} \
  TS_TRITON_SHMEM_GRID_CAP=${GRID_CAP} \
  TS_TRITON_SHMEM_GRID_CAP_MIN_M=${GRID_CAP_MIN_M} \
  TS_TRITON_SHMEM_ONESHOT_MAX_M=${ONESHOT_MAX_M} \
  TS_TRITON_AR_DISABLE=${TRITON_AR_DISABLE} \
  TS_TRITON_AR_WORKGROUP_SYNC=${TRITON_AR_WORKGROUP_SYNC} \
  TOKENSPEED_PROFILER_DIR=${PROFILER_DIR} \
  TOKENSPEED_PROFILE_WITH_STACK=${PROFILE_WITH_STACK} \
  TOKENSPEED_KERNEL_PROFILE=${KERNEL_PROFILE} \
  TOKENSPEED_KERNEL_PROFILE_EARLY=${KERNEL_PROFILE_EARLY} \
  TOKENSPEED_KERNEL_PROFILE_EARLY_KEEP_ACTIVE=${KERNEL_PROFILE_EARLY_KEEP_ACTIVE} \
  TOKENSPEED_KERNEL_PROFILE_BEFORE_GRAPHS=${KERNEL_PROFILE_BEFORE_GRAPHS} \
  TOKENSPEED_KERNEL_PROFILE_GRAPH_SCOPES=${KERNEL_PROFILE_GRAPH_SCOPES} \
  TOKENSPEED_KERNEL_PROFILE_OUTPUT=${KERNEL_PROFILE_OUTPUT} \
  TOKENSPEED_KERNEL_PROFILE_DATA=${KERNEL_PROFILE_DATA} \
  TOKENSPEED_KERNEL_PROFILE_BACKEND=${KERNEL_PROFILE_BACKEND} \
  TOKENSPEED_KERNEL_PROFILE_HOOK=${KERNEL_PROFILE_HOOK} \
  TOKENSPEED_KERNEL_PROFILE_OUTPUT_FORMAT=${KERNEL_PROFILE_OUTPUT_FORMAT} \
  PYTHONPATH=/home/jeremwan/tokenspeed/tokenspeed-kernel/benchmark:${PYTHONPATH:-} \
  nohup python -m tokenspeed.cli serve /data/models/openai/gpt-oss-120b \
    --served-model-name gpt-oss-120b --host 127.0.0.1 --port ${PORT} \
    --world-size ${WS} --max-model-len 131072 --kv-cache-dtype fp8 \
    --chunked-prefill-size 8192 --max-num-seqs 256 --reasoning-parser base \
    --policy round_robin --kvstore-size 8 --comm-fusion-max-num-tokens ${CAP} \
    --engine-startup-timeout 3600 $* >> ${LOG} 2>&1 & echo SERVE_PID=\$! LOG=${LOG}"
