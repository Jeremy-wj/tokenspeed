#!/usr/bin/env bash
# Launch a model with explicit AR+RMSNorm profile metadata.
# Usage: e2e_arnorm_serve.sh <world_size> <visible_devices> <fusion_cap> <backend> [serve args...]
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"

WS="${1:?world_size}"
HVD="${2:?visible_devices}"
CAP="${3:-${COMM_FUSION_MAX_NUM_TOKENS:-2048}}"
BK="${4:-auto}"
shift 4 || true

MODEL_PATH="${MODEL_PATH:?source an AR+RMSNorm model profile or set MODEL_PATH}"
SERVED_MODEL_NAME="${SERVED_MODEL_NAME:-$(basename "$MODEL_PATH")}"
MODEL_LABEL="${MODEL_LABEL:-$SERVED_MODEL_NAME}"
HIDDEN_SIZE="${HIDDEN_SIZE:?source a model profile or set HIDDEN_SIZE}"
HARDWARE_LABEL="${HARDWARE_LABEL:-unknown-hardware}"
PROFILE_ID="${AR_NORM_PROFILE_ID:-unqualified-manual}"
PROFILE_PURE_TP="${TS_TRITON_SHMEM_PROFILE_PURE_TP:-0}"
AR_NORM_SERVE_ARGS="${AR_NORM_SERVE_ARGS:-}"

PORT="${PORT:-8100}"
CONTAINER="${CONTAINER:-${TOKENSPEED_CONTAINER:-jeremwan-tokenspeed-profiler}}"
CONTAINER_REPO_ROOT="${CONTAINER_REPO_ROOT:-${REPO_ROOT}}"
RESULT_ROOT="${AR_RMSNORM_RESULT_ROOT:-${SCRIPT_DIR}/results/ar_rmsnorm/raw}"
RUN_DATE="${RUN_DATE:-$(date -u +%F)}"
RUN_LABEL="${RUN_LABEL:-${MODEL_LABEL}_tp${WS}_${BK}_cap${CAP}}"
RUN_ROOT="${RUN_ROOT:-${RESULT_ROOT}/runs/${MODEL_LABEL}/${HARDWARE_LABEL}/${RUN_DATE}}"
LOG_DIR="${LOG_DIR:-${RUN_ROOT}/logs}"
LOG="${LOG_DIR}/serve-${RUN_LABEL}.log"

NCCL_BLOCKING_WAIT="${TORCH_NCCL_BLOCKING_WAIT:-0}"
COARSE_SHMEM="${TS_TRITON_SHMEM_COARSE:-1}"
SHMEM_OUTPUT_RING="${TS_TRITON_SHMEM_OUTPUT_RING:-0}"
INPUT_SITE_RING="${TS_TRITON_SHMEM_INPUT_SITE_RING:-0}"
BORROW_TWOSHOT_OUTPUT="${TS_TRITON_SHMEM_BORROW_TWOSHOT_OUTPUT:-0}"
INKERNEL_BARRIER="${TS_TRITON_SHMEM_INKERNEL_BARRIER:-0}"
FOLD_COPYIN="${TS_TRITON_SHMEM_FOLD_COPYIN:-0}"
DOUBLE_BUFFER_INPUT="${TS_TRITON_SHMEM_DOUBLE_BUFFER_INPUT:-0}"
WORKGROUP_SYNC="${TS_TRITON_SHMEM_WORKGROUP_SYNC:-1}"
FOLD_NUM_WARPS="${TS_TRITON_SHMEM_FOLD_NUM_WARPS:-1}"
BARRIER_GRID="${TS_TRITON_SHMEM_BARRIER_GRID:-0}"
GRID_CAP="${TS_TRITON_SHMEM_GRID_CAP:-0}"
GRID_CAP_MIN_M="${TS_TRITON_SHMEM_GRID_CAP_MIN_M:-0}"
ONESHOT_MAX_M="${TS_TRITON_SHMEM_ONESHOT_MAX_M:-256}"
ONESHOT_BLOCK_N="${TS_TRITON_SHMEM_ONESHOT_BLOCK_N:-0}"
ONESHOT_VARIANT="${TS_TRITON_SHMEM_ONESHOT_VARIANT:-auto}"
PADDED_MAX_M="${TS_TRITON_SHMEM_PADDED_MAX_M:-64}"
ONESHOT_NUM_WARPS="${TS_TRITON_SHMEM_ONESHOT_NUM_WARPS:-0}"
TWOSHOT_BLOCK_N="${TS_TRITON_SHMEM_TWOSHOT_BLOCK_N:-0}"
FUSION_MIN_M="${TS_TRITON_SHMEM_FUSION_MIN_M:-0}"
FUSION_MAX_M="${TS_TRITON_SHMEM_FUSION_MAX_M:-0}"
SERIALIZE_KERNEL="${AMD_SERIALIZE_KERNEL:-0}"
SERIALIZE_COPY="${AMD_SERIALIZE_COPY:-0}"
HIP_LAUNCH_BLOCKING_VALUE="${HIP_LAUNCH_BLOCKING:-0}"
GPU_COREDUMP_PATTERN="${HSA_COREDUMP_PATTERN:-}"
GPU_COREDUMP_ENABLED=0
GPU_COREDUMP_ENV=""
if [[ -n "$GPU_COREDUMP_PATTERN" ]]; then
  GPU_COREDUMP_ENABLED=1
  mkdir -p "$(dirname "$GPU_COREDUMP_PATTERN")"
  GPU_COREDUMP_ENV="HSA_COREDUMP_PATTERN='${GPU_COREDUMP_PATTERN}'"
fi

PROFILER_DIR="${TOKENSPEED_PROFILER_DIR:-${RUN_ROOT}/profiles}"
PROFILE_WITH_STACK="${TOKENSPEED_PROFILE_WITH_STACK:-0}"
PROFILE_FORWARD_MARKERS="${TOKENSPEED_PROFILE_FORWARD_MARKERS:-0}"
ENGINE_MODULE="${TS_SERVE_ENGINE_MODULE:-smg_grpc_servicer.tokenspeed}"
DEEP_HEALTH_MODE="${TOKENSPEED_DEEP_HEALTH_MODE:-generate}"
PASSIVE_HEALTH_STUCK_SEC="${TOKENSPEED_PASSIVE_HEALTH_STUCK_SEC:-30}"
KERNEL_PROFILE="${TOKENSPEED_KERNEL_PROFILE:-0}"
KERNEL_PROFILE_EARLY="${TOKENSPEED_KERNEL_PROFILE_EARLY:-0}"
KERNEL_PROFILE_EARLY_KEEP_ACTIVE="${TOKENSPEED_KERNEL_PROFILE_EARLY_KEEP_ACTIVE:-0}"
KERNEL_PROFILE_BEFORE_GRAPHS="${TOKENSPEED_KERNEL_PROFILE_BEFORE_GRAPHS:-0}"
KERNEL_PROFILE_GRAPH_SCOPES="${TOKENSPEED_KERNEL_PROFILE_GRAPH_SCOPES:-0}"
KERNEL_PROFILE_OUTPUT="${TOKENSPEED_KERNEL_PROFILE_OUTPUT:-${RUN_ROOT}/profiles/proton/profile}"
KERNEL_PROFILE_DATA="${TOKENSPEED_KERNEL_PROFILE_DATA:-tree}"
KERNEL_PROFILE_BACKEND="${TOKENSPEED_KERNEL_PROFILE_BACKEND:-}"
KERNEL_PROFILE_HOOK="${TOKENSPEED_KERNEL_PROFILE_HOOK:-triton}"
KERNEL_PROFILE_OUTPUT_FORMAT="${TOKENSPEED_KERNEL_PROFILE_OUTPUT_FORMAT:-}"

ENABLE_FUSION="${ENABLE_ALLREDUCE_FUSION:-}"
if [[ -z "$ENABLE_FUSION" ]]; then
  if [[ "$BK" != "auto" && "$CAP" -gt 0 ]]; then
    ENABLE_FUSION=1
  else
    ENABLE_FUSION=0
  fi
fi
if [[ "$ENABLE_FUSION" == "1" ]]; then
  FUSION_ARG="--enable-allreduce-fusion"
else
  FUSION_ARG="--disable-allreduce-fusion"
fi

if [[ "$KERNEL_PROFILE_BACKEND" == "rocprofiler" || "$KERNEL_PROFILE_BACKEND" == "roctracer" ]]; then
  DEVICE_VISIBILITY="ROCR_VISIBLE_DEVICES=${HVD}"
else
  DEVICE_VISIBILITY="HIP_VISIBLE_DEVICES=${HVD}"
fi

IFS=',' read -r -a DEVICES <<< "$HVD"
if [[ "${#DEVICES[@]}" -ne "$WS" ]]; then
  echo "world_size=$WS but visible_devices contains ${#DEVICES[@]} devices" >&2
  exit 2
fi

KERNEL_PROFILE_OUTPUT_DIR="$(dirname "$KERNEL_PROFILE_OUTPUT")"
mkdir -p "$LOG_DIR" "$PROFILER_DIR" "$KERNEL_PROFILE_OUTPUT_DIR"
docker exec "$CONTAINER" bash -lc "mkdir -p '${LOG_DIR}' '${PROFILER_DIR}' '${KERNEL_PROFILE_OUTPUT_DIR}'; cd '${CONTAINER_REPO_ROOT}' && \
  printf 'RUN_ENV MODEL=%s HIDDEN=%s HARDWARE=%s PROFILE_ID=%s PROFILE_PURE_TP=%s HVD=%s WS=%s CAP=%s BACKEND=%s ENABLE_FUSION=%s BLOCKING_WAIT=%s COARSE=%s SHMEM_OUTPUT_RING=%s INPUT_SITE_RING=%s BORROW_TWOSHOT_OUTPUT=%s INKERNEL=%s FOLD_COPYIN=%s DOUBLE_BUFFER_INPUT=%s WORKGROUP_SYNC=%s FOLD_NUM_WARPS=%d BARRIER_GRID=%s GRID_CAP=%s GRID_CAP_MIN_M=%s ONESHOT_MAX_M=%s ONESHOT_BLOCK_N=%s ONESHOT_VARIANT=%s PADDED_MAX_M=%s ONESHOT_NUM_WARPS=%s TWOSHOT_BLOCK_N=%s FUSION_MIN_M=%s FUSION_MAX_M=%s SERIALIZE_KERNEL=%s SERIALIZE_COPY=%s HIP_LAUNCH_BLOCKING=%s GPU_COREDUMP=%s FORWARD_MARKERS=%s ENGINE_MODULE=%s DEEP_HEALTH_MODE=%s PASSIVE_HEALTH_STUCK_SEC=%s\\n' \
    '${MODEL_LABEL}' '${HIDDEN_SIZE}' '${HARDWARE_LABEL}' '${PROFILE_ID}' '${PROFILE_PURE_TP}' '${HVD}' '${WS}' '${CAP}' '${BK}' '${ENABLE_FUSION}' \
    '${NCCL_BLOCKING_WAIT}' '${COARSE_SHMEM}' '${SHMEM_OUTPUT_RING}' '${INPUT_SITE_RING}' '${BORROW_TWOSHOT_OUTPUT}' '${INKERNEL_BARRIER}' '${FOLD_COPYIN}' '${DOUBLE_BUFFER_INPUT}' '${WORKGROUP_SYNC}' \
    '${FOLD_NUM_WARPS}' '${BARRIER_GRID}' '${GRID_CAP}' '${GRID_CAP_MIN_M}' \
    '${ONESHOT_MAX_M}' '${ONESHOT_BLOCK_N}' '${ONESHOT_VARIANT}' '${PADDED_MAX_M}' '${ONESHOT_NUM_WARPS}' '${TWOSHOT_BLOCK_N}' '${FUSION_MIN_M}' '${FUSION_MAX_M}' \
    '${SERIALIZE_KERNEL}' '${SERIALIZE_COPY}' '${HIP_LAUNCH_BLOCKING_VALUE}' '${GPU_COREDUMP_ENABLED}' \
    '${PROFILE_FORWARD_MARKERS}' '${ENGINE_MODULE}' '${DEEP_HEALTH_MODE}' '${PASSIVE_HEALTH_STUCK_SEC}' > '${LOG}'; \
  umask 000; \
  ${GPU_COREDUMP_ENV} ${DEVICE_VISIBILITY} TS_ARNORM_BACKEND='${BK}' \
  AR_NORM_PROFILE_ID='${PROFILE_ID}' \
  AR_NORM_DEVICES='${HVD}' \
  TS_TRITON_SHMEM_PROFILE_PURE_TP='${PROFILE_PURE_TP}' \
  TS_TRITON_SHMEM_VISIBLE_DEVICES='${HVD}' HSA_ENABLE_IPC_MODE_LEGACY=1 \
  TORCH_NCCL_BLOCKING_WAIT='${NCCL_BLOCKING_WAIT}' \
  TS_TRITON_SHMEM_COARSE='${COARSE_SHMEM}' \
  TS_TRITON_SHMEM_OUTPUT_RING='${SHMEM_OUTPUT_RING}' \
  TS_TRITON_SHMEM_INPUT_SITE_RING='${INPUT_SITE_RING}' \
  TS_TRITON_SHMEM_BORROW_TWOSHOT_OUTPUT='${BORROW_TWOSHOT_OUTPUT}' \
  TS_TRITON_SHMEM_INKERNEL_BARRIER='${INKERNEL_BARRIER}' \
  TS_TRITON_SHMEM_FOLD_COPYIN='${FOLD_COPYIN}' \
  TS_TRITON_SHMEM_DOUBLE_BUFFER_INPUT='${DOUBLE_BUFFER_INPUT}' \
  TS_TRITON_SHMEM_WORKGROUP_SYNC='${WORKGROUP_SYNC}' \
  TS_TRITON_SHMEM_FOLD_NUM_WARPS='${FOLD_NUM_WARPS}' \
  TS_TRITON_SHMEM_BARRIER_GRID='${BARRIER_GRID}' \
  TS_TRITON_SHMEM_GRID_CAP='${GRID_CAP}' \
  TS_TRITON_SHMEM_GRID_CAP_MIN_M='${GRID_CAP_MIN_M}' \
  TS_TRITON_SHMEM_ONESHOT_MAX_M='${ONESHOT_MAX_M}' \
  TS_TRITON_SHMEM_ONESHOT_BLOCK_N='${ONESHOT_BLOCK_N}' \
  TS_TRITON_SHMEM_ONESHOT_VARIANT='${ONESHOT_VARIANT}' \
  TS_TRITON_SHMEM_PADDED_MAX_M='${PADDED_MAX_M}' \
  TS_TRITON_SHMEM_ONESHOT_NUM_WARPS='${ONESHOT_NUM_WARPS}' \
  TS_TRITON_SHMEM_TWOSHOT_BLOCK_N='${TWOSHOT_BLOCK_N}' \
  TS_TRITON_SHMEM_FUSION_MIN_M='${FUSION_MIN_M}' \
  TS_TRITON_SHMEM_FUSION_MAX_M='${FUSION_MAX_M}' \
  AMD_SERIALIZE_KERNEL='${SERIALIZE_KERNEL}' \
  AMD_SERIALIZE_COPY='${SERIALIZE_COPY}' \
  HIP_LAUNCH_BLOCKING='${HIP_LAUNCH_BLOCKING_VALUE}' \
  TOKENSPEED_PROFILER_DIR='${PROFILER_DIR}' \
  TOKENSPEED_PROFILE_WITH_STACK='${PROFILE_WITH_STACK}' \
  TOKENSPEED_PROFILE_FORWARD_MARKERS='${PROFILE_FORWARD_MARKERS}' \
  TS_SERVE_ENGINE_MODULE='${ENGINE_MODULE}' \
  TOKENSPEED_DEEP_HEALTH_MODE='${DEEP_HEALTH_MODE}' \
  TOKENSPEED_PASSIVE_HEALTH_STUCK_SEC='${PASSIVE_HEALTH_STUCK_SEC}' \
  TOKENSPEED_KERNEL_PROFILE='${KERNEL_PROFILE}' \
  TOKENSPEED_KERNEL_PROFILE_EARLY='${KERNEL_PROFILE_EARLY}' \
  TOKENSPEED_KERNEL_PROFILE_EARLY_KEEP_ACTIVE='${KERNEL_PROFILE_EARLY_KEEP_ACTIVE}' \
  TOKENSPEED_KERNEL_PROFILE_BEFORE_GRAPHS='${KERNEL_PROFILE_BEFORE_GRAPHS}' \
  TOKENSPEED_KERNEL_PROFILE_GRAPH_SCOPES='${KERNEL_PROFILE_GRAPH_SCOPES}' \
  TOKENSPEED_KERNEL_PROFILE_OUTPUT='${KERNEL_PROFILE_OUTPUT}' \
  TOKENSPEED_KERNEL_PROFILE_DATA='${KERNEL_PROFILE_DATA}' \
  TOKENSPEED_KERNEL_PROFILE_BACKEND='${KERNEL_PROFILE_BACKEND}' \
  TOKENSPEED_KERNEL_PROFILE_HOOK='${KERNEL_PROFILE_HOOK}' \
  TOKENSPEED_KERNEL_PROFILE_OUTPUT_FORMAT='${KERNEL_PROFILE_OUTPUT_FORMAT}' \
  PYTHONPATH='${CONTAINER_REPO_ROOT}/tokenspeed-kernel-amd/python:${CONTAINER_REPO_ROOT}/tokenspeed-kernel/python:${CONTAINER_REPO_ROOT}/python:${CONTAINER_REPO_ROOT}/tokenspeed-kernel/benchmark':${PYTHONPATH:-} \
  nohup python -m tokenspeed.cli serve '${MODEL_PATH}' \
    --served-model-name '${SERVED_MODEL_NAME}' --host 127.0.0.1 --port '${PORT}' \
    --world-size '${WS}' --comm-fusion-max-num-tokens '${CAP}' \
    ${FUSION_ARG} ${AR_NORM_SERVE_ARGS} --engine-startup-timeout 3600 $* \
    >> '${LOG}' 2>&1 & echo SERVE_PID=\$! LOG='${LOG}'"

